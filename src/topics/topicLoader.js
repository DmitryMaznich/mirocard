function normalizeTextValue(value, fallback = "") {
  if (value == null) return fallback;
  if (Array.isArray(value)) {
    const lines = value.map((item) => normalizeTextValue(item, "")).filter(Boolean);
    return lines.length ? lines.join("\n") : fallback;
  }
  if (typeof value === "string") return value;
  if (typeof value === "object") return normalizeTextValue(value.ru ?? value.en, fallback);
  return String(value);
}

function normalizeTextList(value, fallback = []) {
  if (value == null) return fallback;
  if (Array.isArray(value)) {
    const out = value.map((item) => normalizeTextValue(item, "")).filter(Boolean);
    return out.length ? out : fallback;
  }
  const single = normalizeTextValue(value, "");
  return single ? [single] : fallback;
}

function getParamValueLabel(def, value) {
  const labels = def?.labels?.ru ?? def?.labels ?? {};
  return normalizeTextValue(labels?.[value], String(value));
}

function describeModeParams(params = {}) {
  const rows = Object.entries(params).map(([key, def]) => {
    const label = normalizeTextValue(def?.label, key);
    const hint = normalizeTextValue(def?.hint, "");

    if (def?.type === "concept_selector") {
      return `${label || "Понятия"}: выберите карточки или понятия, которые нужны именно для этого занятия.`;
    }

    if (def?.type === "enum") {
      const values = (def.values ?? []).map((value) => getParamValueLabel(def, value)).join(" / ");
      const defaultText = def.default != null ? ` По умолчанию: ${getParamValueLabel(def, def.default)}.` : "";
      return `${label}: ${values || "варианты выбираются на экране настроек"}.${defaultText}${hint ? ` ${hint}` : ""}`;
    }

    if (def?.type === "number") {
      const range = [def.min, def.max].filter((value) => value != null).join("-");
      const defaultText = def.default != null ? ` По умолчанию: ${def.default}.` : "";
      return `${label}: ${range ? `диапазон ${range}` : "числовая настройка"}.${defaultText}${hint ? ` ${hint}` : ""}`;
    }

    if (def?.type === "boolean") {
      const defaultText = def.default != null ? ` По умолчанию: ${def.default ? "включено" : "выключено"}.` : "";
      return `${label}: включить или выключить.${defaultText}${hint ? ` ${hint}` : ""}`;
    }

    return `${label}: настройка режима.`;
  }).filter(Boolean);

  return rows.length
    ? rows
    : ["Дополнительных настроек нет: логопед работает в базовом сценарии режима."];
}

function getFallbackModeGoal(mode) {
  const title = normalizeTextValue(mode?.ui?.title, "режим");
  return `Ребёнок выполняет режим «${title}» стабильно и переносит навык в занятие без лишних подсказок.`;
}

function normalizeModeMethodology(mode, renderer) {
  const defaults = DEFAULT_MODE_METHODOLOGY[renderer]?.[mode.id] ?? {};
  // defaults wins over mode.methodology for any key it defines — mode.methodology can
  // only be a stale snapshot of a previous run of this same DEFAULT_MODE_METHODOLOGY
  // entry for known default modes (no shipped manifest ever authors its own mode
  // methodology), so pinning to whatever was persisted first would mean edits to this
  // text never reach already-installed records. mode.methodology still supplies any
  // key defaults doesn't define, which matters for genuinely custom (non-default) modes.
  const raw = { ...(mode.methodology ?? {}), ...defaults };
  const text = normalizeTextValue(raw.text ?? raw.description ?? mode.ui?.instruction, "");
  const summary = normalizeTextValue(raw.summary, text || normalizeTextValue(mode.ui?.instruction, ""));
  const settings = normalizeTextList(raw.settings, describeModeParams(mode.params));
  const goal = normalizeTextValue(raw.goal ?? raw.finalGoal, getFallbackModeGoal(mode));
  const tips = normalizeTextList(raw.tips, []);
  const duration = normalizeTextValue(raw.duration, "");

  return {
    ...raw,
    text,
    summary,
    settings,
    goal,
    tips,
    duration,
  };
}

function normalizeTopicAbout(about, renderer) {
  const defaults = DEFAULT_TOPIC_ABOUT[renderer] ?? DEFAULT_TOPIC_ABOUT.flashcards;
  const aboutObject = about && typeof about === "object" && !Array.isArray(about) ? about : {};
  const legacyLines = normalizeTextList(
    Array.isArray(about) ? about : (aboutObject.ru ?? aboutObject.en),
    []
  );
  const raw = { ...defaults, ...aboutObject };
  // A legacy `about.ru: [...]` is authored copy, not an invitation to insert
  // unrelated renderer-wide goals and study steps above it.
  const hasLegacy = legacyLines.length > 0;
  const description = normalizeTextValue(aboutObject.description ?? aboutObject.text, legacyLines[0] ?? defaults.description);
  const goals = normalizeTextList(aboutObject.goals, hasLegacy ? [] : defaults.goals ?? []);
  const finalGoal = normalizeTextValue(aboutObject.finalGoal ?? aboutObject.goal, hasLegacy ? "" : defaults.finalGoal);
  const flowFallback = hasLegacy ? legacyLines.slice(1) : defaults.flow ?? [];
  const flow = normalizeTextList(aboutObject.flow ?? aboutObject.tips, flowFallback);
  const duration = normalizeTextValue(raw.duration, "");

  return {
    ...raw,
    description,
    text: normalizeTextValue(aboutObject.text, description),
    goals,
    finalGoal,
    flow,
    duration,
  };
}

function normalizeModeText(mode, renderer) {
  const ui = mode.ui ?? {};
  const withUi = {
    ...mode,
    ui: {
      ...ui,
      title: normalizeTextValue(ui.title, mode.id),
      instruction: normalizeTextValue(ui.instruction, ""),
    },
  };

  return {
    ...withUi,
    methodology: normalizeModeMethodology(withUi, renderer),
  };
}

function ensureModeIcons(modes = [], renderer) {
  const normalizedModes = modes.map((mode) => normalizeModeText(mode, renderer));
  const fallback = MODE_ICON_FALLBACKS[renderer]?.default ?? null;
  if (!fallback) return normalizedModes;
  return normalizedModes.map((mode) => {
    if (mode.ui?.icon) return mode;
    return {
      ...mode,
      ui: {
        ...(mode.ui ?? {}),
        icon: fallback,
      },
    };
  });
}

// ui and params are code-owned for default modes — no shipped topic manifest defines
// its own "modes" array (verified across public/*.json), so whatever is persisted
// under these keys on an already-installed record can only be a stale snapshot of a
// PREVIOUS run of this very DEFAULT_MODES data, never a genuine user/manifest
// customization. The current code should always fully replace it — both to refresh
// changed values (renamed labels, new icon paths, a param's widget type changing) and
// to drop keys that no longer exist (e.g. the old `level` param renamed to `maxOnes`).
// (methodology text is handled the same way, separately, in normalizeModeMethodology.)
function preferCurrentDefault(defValue) {
  return defValue ?? {};
}

function mergeDefaultModes(existingModes = [], defaultModes = []) {
  const existingById = Object.fromEntries(existingModes.map((mode) => [mode.id, mode]));
  const defaultIds = new Set(defaultModes.map((mode) => mode.id));
  const mergedDefaults = defaultModes.map((def) => {
    const existing = existingById[def.id];
    if (!existing) return def;
    return {
      ...def,
      ...existing,
      ui:     preferCurrentDefault(def.ui),
      params: preferCurrentDefault(def.params),
      ...(["group_ten", "build_number", "identify_number", "exchange_ten"].includes(def.id) ? { orientationLock: def.orientationLock } : {}),
    };
  });
  const customModes = existingModes.filter((mode) => !defaultIds.has(mode.id));
  return [...mergedDefaults, ...customModes];
}

// addition_subtraction's mode order lives in its published deck manifest, and
// mergeDefaultModesKeepOrder only appends new defaults at the end. The finger
// modes (moved in from column_addition) belong inside the ladder, so the order
// is pinned here for both fresh imports and already-installed records.
// operation_audio is manifest-only (no DEFAULT_MODES entry), so its number is
// set here too.
const ADDITION_SUBTRACTION_ORDER = [
  "fingers_show",
  "operation_observe",
  "operation_name_action",
  "operation_do_action",
  "operation_action_from_sign",
  "operation_find_sign",
  "fingers_count",
  "operation_result",
  "operation_chain",
  "operation_worksheet",
  "operation_missing_term",
  "operation_audio",
];

// «Разряды числа» shows its numbered items in DEFAULT_MODES order even for a
// record installed before items were added (merging appends new ones last).
function orderPlaceValueModes(modes) {
  const order = DEFAULT_MODES.place_value.map((m) => m.id);
  const rank = (mode) => (order.includes(mode.id) ? order.indexOf(mode.id) : order.length);
  return [...modes].sort((a, b) => rank(a) - rank(b));
}

function orderAdditionSubtractionModes(modes) {
  const rank = (mode) => {
    const index = ADDITION_SUBTRACTION_ORDER.indexOf(mode.id);
    return index === -1 ? ADDITION_SUBTRACTION_ORDER.length : index;
  };
  return [...modes]
    .sort((a, b) => rank(a) - rank(b))
    .map((mode) => mode.id === "operation_audio"
      ? { ...mode, ui: { ...(mode.ui ?? {}), title: "12. Слушай и посчитай" } }
      : mode);
}

// Preserves manifest mode order; only appends default modes absent from manifest
function mergeDefaultModesKeepOrder(manifestModes = [], defaultModes = []) {
  const defaultById = Object.fromEntries(defaultModes.map((m) => [m.id, m]));
  const manifestIds = new Set(manifestModes.map((m) => m.id));
  const merged = manifestModes.map((mode) => {
    const def = defaultById[mode.id];
    if (!def) return mode;
    return {
      ...def,
      ...mode,
      ui:     preferCurrentDefault(def.ui),
      params: preferCurrentDefault(def.params),
    };
  });
  const missing = defaultModes.filter((m) => !manifestIds.has(m.id));
  return [...merged, ...missing];
}

function mergeDefaultMeta(meta, renderer) {
  const merged = {
    ...(DEFAULT_META[renderer] ?? {}),
    ...meta,
  };
  return {
    ...merged,
    about: normalizeTopicAbout(merged.about, renderer),
  };
}

function normalizeLabel(card) {
  const raw = card.label ?? card.labels;
  if (!raw) return card.answerKey ?? card.id;
  if (typeof raw === "string") return raw;
  return raw.ru ?? raw.en ?? card.answerKey ?? card.id;
}

function normalizeFlashcards(manifest) {
  if (manifest.meta.renderer && manifest.meta.renderer !== "flashcards") return manifest;
  if (manifest.meta.cardType === "procedural") return manifest;

  const meta = mergeDefaultMeta({ ...manifest.meta, renderer: "flashcards" }, "flashcards");

  // card.primary must pass through as-is, not default to true: a card that
  // simply omits the field (as opposed to explicitly setting false) is a
  // non-primary variation of some other card's concept, and deriveConcepts
  // already defaults a concept with zero explicit-primary cards to its first
  // card. Defaulting every card to primary here made every omitted-flag
  // secondary card outrank the concept's real primary card wherever
  // anything reads card.primary directly (deriveConcepts's "last primary
  // card wins" merge, generateEmotionControlTasks's vocabulary filter) -
  // confirmed live on people_names, whose secondary cards omit the field.
  const cards = manifest.cards.map((card) => ({
    ...card,
    label:     normalizeLabel(card),
    conceptId: card.conceptId ?? card.id,
    primary:   card.primary,
  }));

  const modes = ensureModeIcons(buildFlashcardModes(manifest.meta, manifest.modes), "flashcards");

  return { ...manifest, meta, cards, modes };
}

function normalizeProcedural(manifest) {
  if (manifest.meta.renderer === "reading") return manifest;
  // normalizeFlashcards is the dedicated, authoritative normalizer for this
  // renderer and runs right after this function - never let this one touch
  // flashcards manifests first. "flashcards" is a knownRenderer below purely
  // because it happens to have entries in DEFAULT_META/MODE_ICON_FALLBACKS/
  // DEFAULT_MODE_METHODOLOGY (shared lookup tables, not a signal that this
  // is a procedural-style renderer), so without this guard every flashcards
  // manifest fell through into this function's own card normalization,
  // which defaults a card's primary to true whenever the field is merely
  // omitted (not explicitly false) - silently promoting every non-primary
  // secondary card (e.g. people_names' man_sergey) to primary before
  // normalizeFlashcards even runs.
  if (manifest.meta.renderer === "flashcards") return manifest;
  // Infer meta.renderer from first card's renderer field
  const firstRenderer = manifest.cards?.[0]?.renderer;
  const renderer = manifest.meta.renderer ?? RENDERER_MAP[firstRenderer] ?? firstRenderer ?? "comparison";
  const knownRenderer =
    !!DEFAULT_MODES[renderer]
    || !!DEFAULT_META[renderer]
    || !!DEFAULT_MODE_METHODOLOGY[renderer]
    || !!MODE_ICON_FALLBACKS[renderer];

  if (manifest.meta.cardType !== "procedural" && !knownRenderer) return manifest;

  const meta = mergeDefaultMeta({ ...manifest.meta, renderer }, renderer);

  const cards = (manifest.cards ?? []).map((card) => ({
    ...card,
    conceptId: card.conceptId ?? card.id,
    primary:   card.primary   ?? true,
  }));

  const defaultModes = DEFAULT_MODES[renderer] ?? [];
  let modes = manifest.modes?.length
    ? ensureModeIcons(mergeDefaultModesKeepOrder(manifest.modes, defaultModes), renderer)
    : ensureModeIcons(defaultModes, renderer);
  if (renderer === "addition_subtraction") modes = orderAdditionSubtractionModes(modes);
  if (renderer === "place_value") modes = orderPlaceValueModes(modes);

  return { ...manifest, meta, cards, modes };
}

function normalizeReading(manifest) {
  if (manifest.meta.renderer !== "reading" && (manifest.meta.renderer != null || !Array.isArray(manifest.texts))) return manifest;

  const meta = mergeDefaultMeta({ ...manifest.meta, renderer: "reading" }, "reading");
  const cards = Array.isArray(manifest.cards) ? manifest.cards : [];
  const texts = (manifest.texts ?? []).map((text) => ({
    ...text,
    kind: text.kind ?? "prose",
    lines: text.lines ?? [],
    questions: text.questions ?? [],
  }));
  // mergeDefaultModes unions in every DEFAULT_MODES.reading entry regardless
  // of what the deck's own manifest declares — fine for decks that want the
  // full read/understand/assemble set "for free", but some decks (e.g. one
  // that only wants supervised reading, no built-in comprehension quiz or
  // word-scramble) need to actually drop a default mode, not just skip
  // listing it. meta.excludeDefaultModes is that opt-out, scoped per deck.
  const excludedModeIds = new Set(manifest.meta?.excludeDefaultModes ?? []);
  const defaultModesForTopic = excludedModeIds.size
    ? DEFAULT_MODES.reading.filter((m) => !excludedModeIds.has(m.id))
    : DEFAULT_MODES.reading;
  const modes = manifest.modes?.length
    ? ensureModeIcons(mergeDefaultModes(manifest.modes, defaultModesForTopic), "reading")
    : ensureModeIcons(defaultModesForTopic, "reading");

  return { ...manifest, meta, cards, texts, modes };
}

function inferMimeType(filename) {
  if (filename.endsWith(".svg"))  return "image/svg+xml";
  if (filename.endsWith(".png"))  return "image/png";
  if (filename.endsWith(".jpg") || filename.endsWith(".jpeg")) return "image/jpeg";
  if (filename.endsWith(".webp")) return "image/webp";
  if (filename.endsWith(".mp3"))  return "audio/mpeg";
  if (filename.endsWith(".wav"))  return "audio/wav";
  if (filename.endsWith(".ogg"))  return "audio/ogg";
  if (filename.endsWith(".pdf"))  return "application/pdf";
  return "application/octet-stream";
}

// Returns authoritative evaluation/rewardThreshold from DEFAULT_MODES for a given renderer+modeId.
// Used to override stale stored values in topicRecords (IndexedDB may hold old evaluation:"none").
export function getDefaultModeSettings(renderer, modeId) {
  const m = DEFAULT_MODES[renderer]?.find((d) => d.id === modeId);
  if (!m) return null;
  return {
    evaluation:      m.evaluation,
    rewardThreshold: m.rewardThreshold ?? null,
  };
}

export async function importTopic(db, zipBuffer, appVersion = "0.0.0", { origin, installedContent = {}, keepFiles = [], installation, coreBuffer } = {}) {
  const zip = await JSZip.loadAsync(zipBuffer);

  let manifest = await parseManifest(zip);
  manifest = await loadTopicLanguages(manifest, (path) => zip.file(path)?.async("string"), { allowMissingContent: Boolean(manifest.languageContract?.delivery), installedContent });
  manifest = normalizeReading(manifest);
  manifest = normalizeProcedural(manifest);
  manifest = normalizeFlashcards(manifest);
  validateManifest(manifest, appVersion);
  validateImages(manifest, zip);

  const topicId = manifest.meta.id;
  // Marks a deck loaded via manual ZIP upload (as opposed to the shared
  // catalog) so the "Мои темы" section can single it out.
  if (origin) manifest.meta.origin = origin;

  // Pre-resolve card image paths to inline base64 data URLs so bundled
  // renderer IIFEs can access them via topicRecord.cards[n].photo without
  // making additional async calls back to the host app.
  const cardImageUrls = {};
  for (const card of manifest.cards ?? []) {
    if (!card.image) continue;
    const imgFile = zip.file(card.image);
    if (!imgFile) continue;
    const ab    = await imgFile.async("arraybuffer");
    const bytes = new Uint8Array(ab);
    let binary  = "";
    const chunk = 8192;
    for (let i = 0; i < bytes.length; i += chunk) {
      binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
    }
    cardImageUrls[card.id] = `data:${inferMimeType(card.image)};base64,${btoa(binary)}`;
  }

  // Prepare outside the transaction. Quota/write failures leave the old topic intact.
  const files = {};
  for (const filename of Object.keys(zip.files)) {
    if (zip.files[filename].dir || filename === "topic.json" || filename === "deck.json") continue;
    files[filename] = { buf: await zip.files[filename].async("arraybuffer"), type: inferMimeType(filename) };
  }

  // Pre-resolve scene image and audio paths to base64 data URLs (same approach as card images)
  const sceneAssetUrls = {};
  for (const scene of manifest.scenes ?? []) {
    for (const field of ["image", "audio"]) {
      const path = scene[field];
      if (!path || sceneAssetUrls[path]) continue;
      const file = zip.file(path);
      if (!file) continue;
      const ab    = await file.async("arraybuffer");
      const bytes = new Uint8Array(ab);
      let binary  = "";
      const chunk = 8192;
      for (let i = 0; i < bytes.length; i += chunk) {
        binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
      }
      sceneAssetUrls[path] = `data:${inferMimeType(path)};base64,${btoa(binary)}`;
    }
  }

  const core = manifest.languageContract?.delivery ? (coreBuffer ?? zipBuffer) : null;
  const installed = installation ?? (core ? { coreSha256: await sha256Bytes(core), coreBytes: core.byteLength, packages: {} } : null);
  const record = applyReleaseTopicCopy({
    ...(installed ? { installation: installed } : {}),
    id: topicId,
    meta: manifest.meta,
    modes: manifest.modes ?? [],
    ...(manifest.languageContract ? { languageContract: manifest.languageContract, languageResources: manifest.languageResources } : {}),
    cards: (manifest.cards ?? []).map((card) => {
      const imageUrl = cardImageUrls[card.id];
      return imageUrl ? { ...card, imageUrl, photo: imageUrl } : card;
    }),
    groups:    manifest.groups    ?? undefined,
    texts:     manifest.texts     ?? undefined,
    // The «Диктант» word bank (propis, propis2): without it the installed record has no words and
    // the words level starts with an empty list ("Нет элементов для диктанта", 2026-10-11).
    words:     manifest.words     ?? undefined,
    turns:     manifest.turns     ?? undefined,
    contact:   manifest.contact   ?? undefined,
    scripts:   manifest.scripts   ?? undefined,
    sentences: manifest.sentences?.length ? manifest.sentences : undefined,
    // Some reading modes carry their editable source alongside the texts,
    // rather than inside an individual card. Keep that data in the installed
    // record as well: otherwise the configuration UI can open an empty editor
    // even though the source deck supplied a default text.
    storyQuiz: manifest.storyQuiz ?? undefined,
    scenes:    (manifest.scenes ?? []).map((scene) => ({
      ...scene,
      image: sceneAssetUrls[scene.image] ?? scene.image,
      audio: sceneAssetUrls[scene.audio] ?? scene.audio,
    })),
    scenarios:  manifest.scenarios  ?? undefined,
    categories: manifest.categories ?? undefined,
    items:      manifest.items      ?? undefined,
    // propis' "Элементы букв" picker (ParamsScreen.jsx) reads this bank off
    // the installed record the same way texts/cards are read above — without
    // it here, the deck's own elements (present in the downloaded ZIP's
    // topic.json, see build-propis-deck.mjs) never survive the IndexedDB
    // install step, so the picker always renders empty (2026-09-17).
    elements:   manifest.elements   ?? undefined,
    // «Широкая/узкая строка» glyph bank, ready sheets and element repeats (propis, propis2): merged
    // into topic.json by build-propis*-deck.mjs. They must survive the install step too, or the
    // wide-row pages see an empty glyph bank (the same trap `elements` fell into above).
    wide:              manifest.wide              ?? undefined,
    wideSheets:        manifest.wideSheets        ?? undefined,
    wideElementRepeat: manifest.wideElementRepeat ?? undefined,
    installedAt: new Date().toISOString(),
  });

  let coreCache = null;
  if (core) {
    const coreZip = await JSZip.loadAsync(new Uint8Array(core));
    const inventory = {};
    for (const [name, file] of Object.entries(coreZip.files)) {
      if (file.dir || name === "topic.json") continue;
      const bytes = await file.async("arraybuffer");
      inventory[name] = { bytes: bytes.byteLength, sha256: await sha256Bytes(bytes) };
    }
    coreCache = { sha256: installed.coreSha256, manifest: JSON.parse(await coreZip.file("topic.json").async("string")), files: inventory };
  }
  await topics.replaceTopic(db, topicId, files, record, { keepFiles, extraValues: { [`topicCore:${topicId}`]: coreCache } });
  // Re-importing an updated copy must replace its cached IIFE on the next launch.
  clearRendererCache(topicId);

  return record;
}

