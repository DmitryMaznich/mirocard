import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
seen = set(); out = []; errors = []
VOW = set("аеёиоуыэюя")
for row in W:
    w, t, pic, note = row[:4]
    if t is None or w in seen: continue
    only = row[4] if len(row) > 4 else None
    seen.add(w)
    W_ = w.upper()
    aligned = only is None and not any(c in "ьъ" for c in w) and \
        not any(c in "еёюя" and (i == 0 or w[i-1] in VOW) for i, c in enumerate(w))
    if only:
        t = ""   # у таких слов только первая буква, звуковых целей нет
    if only is None and not aligned:
        errors.append(f"{w}: не совпадает число звуков и букв, нужен only")
    targets = []
    for L in t:
        if W_.count(L) != 1:
            errors.append(f"{w}: цель {L} встречается {W_.count(L)} раз"); continue
        i = W_.index(L)
        pos = "start" if i == 0 else ("end" if i == len(w) - 1 else "middle")
        if only and pos != "start":
            errors.append(f"{w}: у слова only={only} цель {L} не в начале")
        if pos == "end" and L in "БВГДЖЗ":
            errors.append(f"{w}: звонкая {L} на конце оглушается")
        targets.append({"letter": L, "position": pos})
    out.append({"id": w, "word": w, "pic": pic, "note": note, "aligned": aligned,
                "only": only, "firstLetter": W_[0], "targets": targets, "emoji": EMOJI.get(w)})
if errors:
    print("\n".join(errors)); sys.exit(1)
json.dump({"words": out}, open(os.path.join(here, "words.json"), "w"), ensure_ascii=False, indent=1)
print(len(out), "words")
