// Russian print letters («Печатные») for the propis2 engine: the 33 capitals of «Печатные буквы» (print_letters, after
// V. A. Ilyukhina's «Волшебные линии», docs/print-letters-ilyukhina.md) as a writing style of the Russian language in «Прописи».
// Source of truth: tools/print_letters/topic.json `cards` — drawn in notebook-cell units (1 cell = 50, a letter 2 cells tall:
// top y = 0, baseline y = 100). Never edit the output: change the letter there and run this again.
// Target: the engine's capture frame (src/handwriting/wordEngine.js, as tools/handwriting/latin/build-print.mjs): baseline y = 62,
// capital top y = -42 (two x-heights of 52), so scale by 104/100 and shift. Upright, written apart (`script.joins: false`), capitals
// only (`script.caps`: a typed small letter is written as its capital — Russian children print capitals only).
// Digits and punctuation: the print ones of the Latin styles (tools/handwriting/latin/print_sl.json), the same Arabic digits.
//
// Run: node tools/handwriting/cyrillic/build-print.mjs → tools/handwriting/cyrillic/print.json
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const cards = JSON.parse(readFileSync(here("../../print_letters/topic.json"), "utf8")).cards.filter((c) => c.type === "letter");
const latinPrint = JSON.parse(readFileSync(here("../latin/print_sl.json"), "utf8")).glyphs;

const K = 104 / 100;
const TOP = -42;
const r3 = (n) => Math.round(n * 1000) / 1000;

// paths are M / L / C with absolute "x,y" or "x y" pairs
function mapPath(d) {
  const tokens = d.match(/[MLC]|-?\d*\.?\d+/g);
  const out = [];
  for (let i = 0; i < tokens.length; ) {
    if (/[MLC]/.test(tokens[i])) { out.push(tokens[i]); i += 1; continue; }
    out.push(`${r3(Number(tokens[i]) * K)} ${r3(TOP + Number(tokens[i + 1]) * K)}`);
    i += 2;
  }
  return out.join(" ");
}

const letters = cards.map((c) => ({
  label: c.label,
  kind: "letter",
  sourceLabel: `print_letters-${c.label}`,
  strokes: c.strokes.map((s) => ({ d: mapPath(s.d), name: s.name })),
  stretch: 1,
  noNormalize: true,
  upright: true,
}));
const signs = latinPrint.filter((g) => g.kind !== "letter").map((g) => ({ ...g, sourceLabel: g.sourceLabel?.replace(/^print_sl-/, "print-") }));

writeFileSync(here("print.json"), JSON.stringify({
  note: "GENERATED by tools/handwriting/cyrillic/build-print.mjs from tools/print_letters/topic.json (letters) and tools/handwriting/latin/print_sl.json (digits, signs) — do not edit by hand",
  glyphs: [...letters, ...signs],
}, null, 1) + "\n");
console.log(`✓ tools/handwriting/cyrillic/print.json: ${letters.length} letters, ${signs.length} digits and signs`);
