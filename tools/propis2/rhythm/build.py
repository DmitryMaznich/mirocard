import json, math, re, os
T = math.tan(math.radians(25))
CELL = 18
def slant(d, x0=4):
    nums = re.findall(r"-?\d+(?:\.\d+)?", d)
    out, i = [], 0
    for tok in re.findall(r"[MCL]|-?\d+(?:\.\d+)?", d):
        pass
    toks = re.findall(r"[MCL]|-?\d+(?:\.\d+)?", d)
    res, k = [], 0
    while k < len(toks):
        t = toks[k]
        if t in "MCL": res.append(t); k += 1; continue
        x, y = float(toks[k]), float(toks[k + 1]); k += 2
        res.append(f"{x0 + x + (62 - y) * T:.2f} {y:.2f}")
    return " ".join(res)
